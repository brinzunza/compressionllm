"""Context-free "unique abbreviation" codec: drop letters only when no other word could be meant.

A word is replaced by its shortest letter subsequence (first letter kept) that no other vocabulary
word also contains as a subsequence, so `uique` can only be `unique` and the decoder is a plain
dictionary lookup: no language model, no context, no ambiguity. `the` stays `the` because `t`, `th`,
`te`... are also subsequences of `this`, `that`, `there`, ... Words outside the vocabulary are escaped
as `#word`.

Decoding rules (in this order): `#word` -> word; a vocabulary word -> itself; a unique abbreviation ->
its word; anything else (e.g. text generated by an LLM) is kept literal.
"""
from collections import Counter

from .base import Compressor
from .lm_codec import subseq_candidates


class UniqueCodec(Compressor):
    needs_vocab = True

    def __init__(self, vocab_size=20000, max_word_len=12, **_ignored):
        self.vocab_size, self.max_word_len = vocab_size, max_word_len
        self.enc = None          # word -> token
        self.dec = None          # token -> word

    def fit(self, train_words):
        cnt = Counter(train_words)
        vocab = [w for w, _ in cnt.most_common() if len(w) <= self.max_word_len and w.isalpha()][:self.vocab_size]
        # number of vocabulary words that contain each abbreviation as a subsequence (first letter kept)
        contain = Counter()
        for w in vocab:
            contain.update(subseq_candidates(w))
        enc, dec = {}, {}
        for w in vocab:
            tok = w
            for a in subseq_candidates(w):                 # shortest first; the last candidate is w itself
                if a == w or contain[a] == 1:
                    tok = a
                    break
            enc[w] = tok
            dec[tok] = w
        for w in vocab:                                    # a vocabulary word always decodes to itself
            dec[w] = w
        self.enc, self.dec = enc, dec
        return self

    def compress(self, words, workers=0, progress=False):
        enc = self.enc
        return [enc.get(w) or "#" + w for w in words]

    def decompress(self, tokens, progress=False):
        dec = self.dec
        return [t[1:] if t.startswith("#") else dec.get(t, t) for t in tokens]

    def describe(self):
        return {"kind": "unique", "vocab_size": self.vocab_size, "max_word_len": self.max_word_len,
                "vocab_words": len(self.enc) if self.enc else 0}
